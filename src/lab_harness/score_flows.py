"""
score_flows.py
Score a CICFlowMeter flow CSV with the trained detectors (AI models + the conventional
Threshold IDS) -- the "AI-assisted assessment" side of the lab comparison.

  python score_flows.py lab_run/benign_flows.csv --port 3000 --phase benign --out lab_run/benign_scored.csv
  python score_flows.py lab_run/attack_flows.csv --port 3000 --phase attack --out lab_run/attack_scored.csv

--phase tells the script what the capture contains, so it can report false alarms
(benign phase: every alert is a false positive) or the detection rate (attack phase:
traffic generated by the OWASP ZAP active scan). A <out>.summary.json is written for
compare_with_zap.py.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import joblib
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))                 # models/baseline modules for unpickling
sys.path.insert(0, str(Path(__file__).resolve().parent))
import config  # noqa: E402
import models as M  # noqa: E402,F401  (needed so pickled pipelines can resolve signed_log1p)
from flow_columns import normalize  # noqa: E402

DETECTORS = config.ML_MODELS + [config.BASELINE]


def main():
    ap = argparse.ArgumentParser(description="Score CICFlowMeter flows with the trained detectors.")
    ap.add_argument("flows_csv")
    ap.add_argument("--port", type=int, help="keep only flows to this server port (e.g. 3000 Juice Shop, 80 DVWA)")
    ap.add_argument("--server-ip", help="keep only flows to this server IP")
    ap.add_argument("--phase", choices=["benign", "attack", "unknown"], default="unknown")
    ap.add_argument("--time-unit", choices=["auto", "us", "s"], default="auto")
    ap.add_argument("--detectors", default="all", help="comma list from: " + ",".join(DETECTORS))
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    features = json.loads(config.FEATURES_JSON.read_text())
    df = pd.read_csv(args.flows_csv, low_memory=False)
    X, meta, rep = normalize(df, features, args.time_unit)
    print(f"Input: {len(df):,} flows; format detected: {rep['style']}; time unit: {rep['time_unit']}")
    print(f"  features matched {rep['matched']}/{len(features)}; derived {rep['derived'] or 'none'}; "
          f"filled with benign median {rep['imputed_with_median'] or 'none'}")

    keep = pd.Series(True, index=X.index)
    if args.port is not None:
        if "Dst Port" not in meta:
            sys.exit("--port given but the CSV has no destination-port column")
        keep &= pd.to_numeric(meta["Dst Port"], errors="coerce") == args.port
    if args.server_ip:
        keep &= meta.get("Dst IP", pd.Series("", index=X.index)).astype(str) == args.server_ip
    X, meta = X[keep], meta[keep]
    print(f"  {len(X):,} flows to the target after filtering")
    if X.empty:
        sys.exit("No flows left to score.")

    names = DETECTORS if args.detectors == "all" else args.detectors.split(",")
    out = meta.copy()
    summary = {"phase": args.phase, "n_flows": int(len(X)), "format": rep, "detectors": {}}
    for n in names:
        det = joblib.load(config.MODELS_DIR / f"binary_{n}.joblib")
        pred = det.predict(X)
        score = det.decision_function(X) if n == config.BASELINE else M.attack_score(det, X)
        out[f"{n}_score"], out[f"{n}_alert"] = score, pred
        rate = float(pred.mean())
        summary["detectors"][n] = {"alerts": int(pred.sum()), "alert_rate": rate}
        label = {"benign": "false-positive rate", "attack": "detection rate"}.get(args.phase, "alert rate")
        print(f"  {config.DISPLAY[n]:34s} alerts {int(pred.sum()):6d}   {label}: {rate:.4f}")
    out["phase"] = args.phase
    out.to_csv(args.out, index=False)
    Path(args.out).with_suffix(".summary.json").write_text(json.dumps(summary, indent=2))
    print(f"Wrote {args.out} and {Path(args.out).with_suffix('.summary.json').name}")


if __name__ == "__main__":
    main()
